const { query } = require('../config/database');

const initMySQLTables = async () => {
  // 1. Users
  await query(`
    CREATE TABLE IF NOT EXISTS USERS (
      ID VARCHAR(50) NOT NULL COMMENT 'Khóa chính định danh duy nhất của tài khoản',
      EMAIL VARCHAR(120) NOT NULL COMMENT 'Địa chỉ email đăng nhập',
      PASSWORD VARCHAR(255) NOT NULL COMMENT 'Mật khẩu đã được mã hóa BCrypt',
      FULL_NAME VARCHAR(100) NOT NULL COMMENT 'Họ và tên đầy đủ',
      PHONE VARCHAR(20) NULL COMMENT 'Số điện thoại',
      ROLE VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER' COMMENT 'SUPER_ADMIN, ADMIN, STAFF, CUSTOMER',
      STATUS VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE, BLOCKED, PENDING',
      AVATAR_URL VARCHAR(500) NULL COMMENT 'URL ảnh đại diện',
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID),
      UNIQUE KEY UK_USERS_EMAIL (EMAIL)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 2. Data Sources (Bảng DATA_SOUSES quản lý tệp media, ảnh Cloudinary)
  await query(`
    CREATE TABLE IF NOT EXISTS DATA_SOUSES (
      ID BIGINT NOT NULL AUTO_INCREMENT COMMENT 'Khóa chính tự tăng',
      FILE_NAME VARCHAR(255) NOT NULL COMMENT 'Tên tệp tin',
      ORIGINAL_NAME VARCHAR(255) NOT NULL COMMENT 'Tên tệp gốc',
      MIME_TYPE VARCHAR(100) NOT NULL COMMENT 'Mime type',
      FILE_SIZE BIGINT NOT NULL COMMENT 'Kích thước bytes',
      CLOUDINARY_URL VARCHAR(500) NULL COMMENT 'URL Cloudinary',
      PUBLIC_ID VARCHAR(255) NULL COMMENT 'Cloudinary public ID',
      STATUS VARCHAR(30) NOT NULL DEFAULT 'PENDING' COMMENT 'Trạng thái xử lý',
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID),
      KEY IDX_DATA_SOUSES_STATUS (STATUS)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 3. Products
  await query(`
    CREATE TABLE IF NOT EXISTS PRODUCTS (
      ID VARCHAR(50) NOT NULL COMMENT 'Mã định danh sản phẩm',
      NAME VARCHAR(150) NOT NULL COMMENT 'Tên sản phẩm',
      SLUG VARCHAR(160) NOT NULL COMMENT 'Đường dẫn SEO',
      TAGLINE VARCHAR(255) NULL COMMENT 'Khẩu hiệu ngắn',
      CATEGORY VARCHAR(50) NOT NULL COMMENT 'Mã danh mục',
      CATEGORY_NAME VARCHAR(100) NOT NULL COMMENT 'Tên hiển thị danh mục',
      BASE_PRICE DECIMAL(15, 2) NOT NULL DEFAULT 0.00 COMMENT 'Giá gốc',
      DESCRIPTION TEXT NULL COMMENT 'Mô tả tóm tắt',
      LONG_DESCRIPTION LONGTEXT NULL COMMENT 'Mô tả chi tiết',
      TECH_STACK JSON NOT NULL COMMENT 'Mảng công nghệ',
      FEATURED_BADGE VARCHAR(50) NULL COMMENT 'Huy hiệu nổi bật',
      HAS_LIVE_DEMO TINYINT(1) NOT NULL DEFAULT 1 COMMENT 'Có demo dùng thử',
      MOCKUP_TYPE VARCHAR(50) NOT NULL DEFAULT 'business' COMMENT 'Khung giao diện',
      IS_PUBLISHED TINYINT(1) NOT NULL DEFAULT 1 COMMENT 'Trạng thái hiển thị',
      RATING DECIMAL(2, 1) NOT NULL DEFAULT 5.0,
      REVIEWS_COUNT INT NOT NULL DEFAULT 1,
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID),
      UNIQUE KEY UK_PRODUCTS_SLUG (SLUG)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 4. Blogs (Quản lý bài viết)
  await query(`
    CREATE TABLE IF NOT EXISTS BLOGS (
      ID VARCHAR(50) NOT NULL COMMENT 'Mã bài viết',
      TITLE VARCHAR(255) NOT NULL COMMENT 'Tiêu đề bài viết',
      SLUG VARCHAR(260) NOT NULL COMMENT 'Đường dẫn tĩnh',
      EXCERPT TEXT NOT NULL COMMENT 'Mô tả ngắn',
      CONTENT LONGTEXT NOT NULL COMMENT 'Nội dung chi tiết',
      CATEGORY VARCHAR(100) NOT NULL COMMENT 'Chuyên mục',
      TAGS JSON NOT NULL COMMENT 'Tags mảng JSON',
      AUTHOR_NAME VARCHAR(100) NOT NULL COMMENT 'Tác giả',
      AUTHOR_ROLE VARCHAR(100) NULL COMMENT 'Chức danh',
      AUTHOR_AVATAR VARCHAR(500) NULL COMMENT 'Avatar tác giả',
      PUBLISHED_AT VARCHAR(50) NOT NULL COMMENT 'Ngày đăng',
      READ_TIME VARCHAR(30) NOT NULL COMMENT 'Thời lượng đọc',
      COVER_IMAGE VARCHAR(500) NOT NULL COMMENT 'Ảnh bìa',
      IS_FEATURED TINYINT(1) NOT NULL DEFAULT 0 COMMENT 'Nổi bật',
      VIEWS_COUNT INT NOT NULL DEFAULT 0,
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID),
      UNIQUE KEY UK_BLOGS_SLUG (SLUG)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 5. Site Headings (Quản lý tiêu đề website)
  await query(`
    CREATE TABLE IF NOT EXISTS SITE_HEADINGS (
      ID VARCHAR(50) NOT NULL COMMENT 'Mã tiêu đề',
      \`KEY\` VARCHAR(100) NOT NULL COMMENT 'Key định danh',
      SECTION VARCHAR(100) NOT NULL COMMENT 'Khu vực giao diện',
      LABEL VARCHAR(150) NOT NULL COMMENT 'Nhãn quản trị',
      VALUE TEXT NOT NULL COMMENT 'Nội dung hiển thị',
      TYPE VARCHAR(30) NOT NULL COMMENT 'Phân loại',
      PAGE VARCHAR(50) NOT NULL COMMENT 'Trang áp dụng',
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID),
      UNIQUE KEY UK_SITE_HEADINGS_KEY (\`KEY\`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 6. Orders (Đơn hàng mua bản quyền & dùng thử)
  await query(`
    CREATE TABLE IF NOT EXISTS ORDERS (
      ID VARCHAR(50) NOT NULL COMMENT 'Mã hóa đơn',
      CUSTOMER_NAME VARCHAR(100) NOT NULL COMMENT 'Họ tên khách hàng',
      CUSTOMER_EMAIL VARCHAR(120) NOT NULL COMMENT 'Email khách hàng',
      CUSTOMER_PHONE VARCHAR(20) NOT NULL COMMENT 'Số điện thoại',
      CUSTOMER_COMPANY VARCHAR(150) NULL COMMENT 'Công ty',
      TOTAL DECIMAL(15, 2) NOT NULL DEFAULT 0.00 COMMENT 'Tổng tiền',
      STATUS VARCHAR(30) NOT NULL DEFAULT 'DEMO_PENDING',
      PAYMENT_METHOD VARCHAR(30) NOT NULL DEFAULT 'VIETQR',
      PAYMENT_STATUS VARCHAR(30) NOT NULL DEFAULT 'UNPAID',
      NOTES TEXT NULL,
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 7. Consultations (Leads tư vấn giải pháp)
  await query(`
    CREATE TABLE IF NOT EXISTS CONSULTATIONS (
      ID VARCHAR(50) NOT NULL COMMENT 'Mã yêu cầu',
      FULL_NAME VARCHAR(100) NOT NULL COMMENT 'Họ tên',
      PHONE VARCHAR(20) NOT NULL COMMENT 'Số điện thoại',
      EMAIL VARCHAR(120) NULL COMMENT 'Email',
      COMPANY VARCHAR(150) NULL COMMENT 'Công ty',
      SERVICE_INTEREST VARCHAR(150) NOT NULL COMMENT 'Dịch vụ quan tâm',
      ESTIMATED_BUDGET VARCHAR(100) NULL COMMENT 'Ngân sách',
      MESSAGE TEXT NULL COMMENT 'Nội dung',
      STATUS VARCHAR(30) NOT NULL DEFAULT 'NEW',
      CREATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UPDATED_AT TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
      PRIMARY KEY (ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  // 8. Site Settings (Cấu hình thương hiệu)
  await query(`
    CREATE TABLE IF NOT EXISTS SITE_SETTINGS (
      ID INT NOT NULL DEFAULT 1 COMMENT 'Khóa chính',
      BRAND_NAME VARCHAR(100) NOT NULL COMMENT 'Tên thương hiệu',
      BRAND_SUBNAME VARCHAR(150) NOT NULL COMMENT 'Tên bổ trợ',
      SLOGAN VARCHAR(255) NULL COMMENT 'Khẩu hiệu',
      MAIN_MESSAGE VARCHAR(255) NULL COMMENT 'Thông điệp Hero',
      CONTACT_EMAIL VARCHAR(120) NOT NULL COMMENT 'Email liên hệ',
      SUPPORT_EMAIL VARCHAR(120) NULL COMMENT 'Email hỗ trợ',
      HOTLINE VARCHAR(20) NOT NULL COMMENT 'Hotline',
      ADDRESS VARCHAR(255) NOT NULL COMMENT 'Địa chỉ',
      WORKING_HOURS VARCHAR(100) NOT NULL COMMENT 'Giờ làm việc',
      SOCIAL_LINKS JSON NOT NULL COMMENT 'Liên kết mạng xã hội',
      COPYRIGHT_TEXT TEXT NOT NULL COMMENT 'Bản quyền',
      PRIMARY KEY (ID)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
  `);

  console.log('✅ [Schema] Đã khởi tạo các bảng MySQL (kèm DATA_SOUSES) thành công!');
};

module.exports = {
  initMySQLTables,
};
